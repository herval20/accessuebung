    <h1 class="text-5xl font-bold" style="color: #735DA5;">Was ist digitale Barrierefreiheit?</h1>

    <p class="text-lg text-gray-700 mb-4">
      Digitale Barrierefreiheit bedeutet, dass alle Menschen – egal ob mit oder ohne Behinderung – Webseiten, Apps oder digitale Produkte problemlos nutzen können.
    </p>

    <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Wie wird Barrierefreiheit gemessen?</h2>
    <p class="text-lg text-gray-700 mb-4">
      Man prüft, ob ein digitales Produkt die internationalen Standards wie die WCAG (Web Content Accessibility Guidelines) erfüllt. Diese Barrierefreiheitsprüfung erfolgt mit automatischen, manuellen und Hilfsmittel-Tests – und zwar mehrmals im gesamten Projekt.
    </p>

    <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Die drei WCAG-Stufen</h2>
    <ul class="text-lg mb-4 text-left" style="color: #4B4B4B; list-style-type: disc; list-style-position: inside;">
      <li><strong style="color: #D3C5E5;">A:</strong> Grundanforderungen</li>
      <li><strong style="color: #D3C5E5;">AA:</strong> Häufig gesetzlich gefordert (Standardstufe)</li>
      <li><strong style="color: #D3C5E5;">AAA:</strong> Höchster Standard</li>
    </ul>
    <p class="text-lg text-gray-700 mb-4">Aktuell gilt WCAG 2.2 mit 87 Erfolgskriterien. WCAG 3.0 ist noch in Entwicklung.</p>

    <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Die 4 WCAG-Grundprinzipien (POUR)</h2>
    <ul class="text-lg text-left" style="color: #4B4B4B; list-style-type: disc; list-style-position: inside;">
      <li><strong style="color: #D3C5E5;">Wahrnehmbar:</strong> Inhalte müssen sichtbar oder hörbar sein (z. B. Alternativtext, Untertitel).</li>
      <li><strong style="color: #D3C5E5;">Bedienbar:</strong> Alle Funktionen müssen steuerbar sein (z. B. per Tastatur oder Touch).</li>
      <li><strong style="color: #D3C5E5;">Verständlich:</strong> Texte und Bedienung müssen leicht zu verstehen sein.</li>
      <li><strong style="color: #D3C5E5;">Robust:</strong> Die Seite muss auf allen Geräten und mit Hilfsmitteln funktionieren.</li>
    </ul>
