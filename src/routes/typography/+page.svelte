  <h1 class="text-5xl font-bold" style="color: #735DA5;">Typografie und Barrierefreiheit</h1>

  <p class="text-lg text-gray-700 mb-4">
    Barrierefreie Inhalte zu erstellen, bedeutet mehr als nur die Auswahl einer gut lesbaren Schriftart. Menschen mit Einschränkungen wie Sehbehinderungen oder Lernstörungen müssen den Text leicht verstehen können. In diesem Modul geht es darum, Designüberlegungen zu treffen, um Inhalte inklusiver zu gestalten.
  </p>

  <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Schriftarten und ihre Auswirkungen</h2>
  <p class="text-lg text-gray-700 mb-4">
    Gängige Schriftarten wie Arial oder Times New Roman sind in der Regel leichter lesbar. Komplexe Schriftarten können Menschen mit Behinderungen verwirren und das Lesen erschweren.
  </p>

  <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Wichtige Typografieüberlegungen</h2>
  <ul class="text-lg mb-4 text-left" style="color: #4B4B4B; list-style-type: disc; list-style-position: inside;">
    <li><strong style="color: #D3C5E5;">Buchstabenmerkmale und Kerning:</strong> Achte darauf, dass Buchstaben klar und eindeutig sind, damit keine Verwechslungen entstehen (z. B. 'I' vs 'l' oder '1').</li>
    <li><strong style="color: #D3C5E5;">Schriftgröße und Stil:</strong> Verwende größere, klare Schriftgrößen und vermeide Kursivschrift und zu kleine Schriftgrößen.</li>
    <li><strong style="color: #D3C5E5;">Struktur und Layout:</strong> Verwende klare Absätze, Überschriften und einen geeigneten Abstand, um den Text leichter verständlich zu machen.</li>
  </ul>

  <h2 class="text-2xl font-bold mb-4" style="color: #735DA5;">Best Practices</h2>
  <ul class="text-lg mb-4 text-left" style="color: #4B4B4B; list-style-type: disc; list-style-position: inside;">
    <li>Verwende gängige Schriftarten wie Arial oder Verdana.</li>
    <li>Vermeide handgeschriebene und verschnörkelte Schriftarten.</li>
    <li>Stelle sicher, dass der Text gut lesbar ist, indem du klare Schriftgrößen und ausreichend Abstand verwendest.</li>
    <li>Verwende Markup anstelle von Text auf Bildern.</li>
  </ul>


